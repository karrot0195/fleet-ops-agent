"""Per-VM per-tool record rendering."""

from __future__ import annotations

import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from .state import utcnow


_RECORD_TEMPLATE = """\
# Fleet Record: {tool} — {ip}

| Field | Value |
|-------|-------|
| **Tool** | {tool} |
| **IP** | {ip} |
| **Run ID** | {run_id} |
| **Survey Verdict** | {verdict} |
| **Installed Version** | {installed_version} |
| **Candidate Version** | {candidate_version} |
| **Precheck OK** | {precheck_ok} |
| **Execution State** | {exec_state} |
| **Rollback State** | {rollback_state} |
| **Timestamps** | survey: {survey_at}, execute: {exec_at} |
| **Evidence** | ```\n{evidence}\n``` |

---

*Generated by fleet-upgrade skill.*
"""


def write_record(
    records_dir: str | Path,
    tool: str,
    ip: str,
    run_id: str,
    verdict: str,
    installed_version: str | None,
    candidate_version: str | None,
    precheck_ok: bool,
    exec_state: str,
    rollback_state: str,
    evidence: str,
) -> Path:
    """Render a per-VM per-tool record to ``plan/{ip}.md`` using the record template."""
    rec_dir = Path(records_dir)
    rec_dir.mkdir(parents=True, exist_ok=True)

    survey_at = utcnow()
    exec_at = utcnow()

    content = _RECORD_TEMPLATE.format(
        tool=tool,
        ip=ip,
        run_id=run_id,
        verdict=verdict,
        installed_version=installed_version or "N/A",
        candidate_version=candidate_version or "N/A",
        precheck_ok="Yes" if precheck_ok else "No",
        exec_state=exec_state,
        rollback_state=rollback_state or "N/A",
        survey_at=survey_at,
        exec_at=exec_at,
        evidence=evidence.strip(),
    )

    filepath = rec_dir / f"{ip}.md"
    filepath.write_text(content, encoding="utf-8")
    return filepath


def format_verdict(verdict: str, reason: str | None = None) -> str:
    """Format a verdict string, optionally including the reason."""
    if reason:
        return f"{verdict}({reason})"
    return verdict
